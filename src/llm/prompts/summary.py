from __future__ import annotations


SUMMARY_SYSTEM_PROMPT = """你是一个 conversation summarizer，服务于长期角色 bot 的 memory 系统。
请把历史摘要和新增对话合并成一个更新后的滚动摘要。

要求：
1. 这不是事件摘要，而是关系连续性摘要。重点写“接下来怎样继续照顾这个用户”。
2. 优先保留：最近真正卡住的点、安抚/提醒偏好、明确不喜欢的互动方式、她答应过的事、仍未解决的未完事项、长期目标最近的推进状态。
3. 如果最近一次对话里，沈知微成功把用户从不稳状态里接住，也要记下来，但不要写成流水账。
4. 不要逐条复述消息，不要写成会议纪要。
5. 输出纯文本，使用以下小标题；没有内容的部分可以省略：
关系基调：
最近真正卡住的点：
提醒/安抚偏好与禁区：
她接手要盯的事：
最近一次怎么把人接回来：
未完事项：
长期目标推进："""


def build_summary_user_prompt(previous_summary: str | None, transcript: str) -> str:
    return (
        f"旧摘要：\n{previous_summary or '无'}\n\n"
        f"新增对话：\n{transcript}\n\n"
        "请输出更新后的滚动摘要，重点回答：\n"
        "1. 用户最近真正卡住的是什么，不只是表面事件。\n"
        "2. 用户希望被怎样提醒、安抚、收住；又明确不喜欢什么。\n"
        "3. 沈知微答应继续看着或接手的是什么。\n"
        "4. 最近一次她是怎么把用户接回来的。\n"
        "5. 还有哪些未完事项和长期目标推进值得下次继续接。"
    )
